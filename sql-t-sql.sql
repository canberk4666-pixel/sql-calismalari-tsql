SELECT 
    C.CITY AS SEHIR, 
    SUM(O.TOTALPRICE) AS TOPLAM_SATIS
FROM ORDERS O
JOIN ADDRESS A ON O.ADRESSID = A.ID
JOIN CITIES C ON A.CITYID = C.ID
GROUP BY C.CITY;

SELECT 
    C.CITY, 
    DATENAME(WEEKDAY, O.[DATE_]) AS DAYOFWEEK, 
    SUM(O.TOTALPRICE) AS TOTALSALE
FROM ORDERS O
JOIN ADDRESS A ON O.ADRESSID = A.ID
JOIN CITIES C ON A.CITYID = C.ID
GROUP BY C.CITY, DATENAME(WEEKDAY, O.[DATE_]), DATEPART(WEEKDAY, O.[DATE_])
ORDER BY C.CITY, DATEPART(WEEKDAY, O.[DATE_]);



SELECT 
    C.CITY,
    SUM(CASE WHEN DATEPART(WEEKDAY, O.[DATE_]) = 2 THEN O.TOTALPRICE ELSE 0 END) AS PAZARTESİ,
    SUM(CASE WHEN DATEPART(WEEKDAY, O.[DATE_]) = 3 THEN O.TOTALPRICE ELSE 0 END) AS SALI,
    SUM(CASE WHEN DATEPART(WEEKDAY, O.[DATE_]) = 4 THEN O.TOTALPRICE ELSE 0 END) AS ÇARŞAMBA,
    SUM(CASE WHEN DATEPART(WEEKDAY, O.[DATE_]) = 5 THEN O.TOTALPRICE ELSE 0 END) AS PERŞEMBE,
    SUM(CASE WHEN DATEPART(WEEKDAY, O.[DATE_]) = 6 THEN O.TOTALPRICE ELSE 0 END) AS CUMA,
    SUM(CASE WHEN DATEPART(WEEKDAY, O.[DATE_]) = 7 THEN O.TOTALPRICE ELSE 0 END) AS CUMARTESİ,
    SUM(CASE WHEN DATEPART(WEEKDAY, O.[DATE_]) = 1 THEN O.TOTALPRICE ELSE 0 END) AS PAZAR
FROM ORDERS O
JOIN ADDRESS A ON O.ADRESSID = A.ID
JOIN CITIES C ON A.CITYID = C.ID
GROUP BY C.CITY;




