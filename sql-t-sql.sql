CREATE TABLE COUNTRIES (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    COUNTRY VARCHAR(50) NOT NULL
);


CREATE TABLE CITIES (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    COUNTRYID INT FOREIGN KEY REFERENCES COUNTRIES(ID),
    CITY VARCHAR(50) NOT NULL
);


CREATE TABLE TOWNS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    CITYID INT FOREIGN KEY REFERENCES CITIES(ID),
    TOWN VARCHAR(50) NOT NULL
);

CREATE TABLE DISTRICTS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    TOWNID INT FOREIGN KEY REFERENCES TOWNS(ID),
    DISTRICT VARCHAR(50) NOT NULL
);


CREATE TABLE USERS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    USERNAME VARCHAR(50) NOT NULL,
    PASSWORD VARCHAR(50) NOT NULL,
    NAMESURNAME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(100),
    GENDER VARCHAR(10),
    BIRTHDATE DATE,
    CREATEDDATE DATETIME DEFAULT GETDATE(),
    TEL1 VARCHAR(20),
    TEL2 VARCHAR(20)
);


CREATE TABLE ADDRESS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    USERID INT FOREIGN KEY REFERENCES USERS(ID),
    COUNTRYID INT FOREIGN KEY REFERENCES COUNTRIES(ID),
    CITYID INT FOREIGN KEY REFERENCES CITIES(ID),
    TOWNID INT FOREIGN KEY REFERENCES TOWNS(ID),
    DISTRICTID INT FOREIGN KEY REFERENCES DISTRICTS(ID),
    POSTALCODE VARCHAR(10),
    ADDRESSTEXT VARCHAR(250)
);

CREATE TABLE ITEMS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    ITEMCODE VARCHAR(50) NOT NULL,
    ITEMNAME VARCHAR(100) NOT NULL,
    UNITPRICE DECIMAL(18,2) NOT NULL,
    CATEGORY1 VARCHAR(50),
    CATEGORY2 VARCHAR(50),
    CATEGORY3 VARCHAR(50),
    CATEGORY4 VARCHAR(50),
    BRAND VARCHAR(40)
);


CREATE TABLE ORDERS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    USERID INT FOREIGN KEY REFERENCES USERS(ID),
    DATE_ DATETIME DEFAULT GETDATE(),
    TOTALPRICE DECIMAL(18,2),
    STATUS_ VARCHAR(30),
    ADRESSID INT FOREIGN KEY REFERENCES ADDRESS(ID)
);


CREATE TABLE ORDERDETAILS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    ORDERID INT FOREIGN KEY REFERENCES ORDERS(ID),
    ITEMID INT FOREIGN KEY REFERENCES ITEMS(ID),
    AMOUNT INT NOT NULL,
    UNITPRICE DECIMAL(18,2) NOT NULL,
    LINETOTAL DECIMAL(18,2) NOT NULL
);


CREATE TABLE INVOICES (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    ORDERID INT FOREIGN KEY REFERENCES ORDERS(ID),
    DATE_ DATETIME DEFAULT GETDATE(),
    ADRESSID INT FOREIGN KEY REFERENCES ADDRESS(ID),
    CARGOFICHENO VARCHAR(50),
    TOTALPRICE DECIMAL(18,2) NOT NULL
);


CREATE TABLE INVOICEDETAILS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    INVOICEID INT FOREIGN KEY REFERENCES INVOICES(ID),
    ORDERDETAILID INT FOREIGN KEY REFERENCES ORDERDETAILS(ID),
    ITEMID INT FOREIGN KEY REFERENCES ITEMS(ID),
    AMOUNT INT NOT NULL,
    UNITPRICE DECIMAL(18,2) NOT NULL,
    LINETOTAL DECIMAL(18,2) NOT NULL
);


CREATE TABLE PAYMENTS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    ORDERID INT FOREIGN KEY REFERENCES ORDERS(ID),
    PAYMENTTYPE VARCHAR(50),
    DATE_ DATETIME DEFAULT GETDATE(),
    APPROVECODE VARCHAR(50),
    PAYMENTTOTAL DECIMAL(18,2) NOT NULL
);


